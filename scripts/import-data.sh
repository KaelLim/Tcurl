#!/usr/bin/env bash
# =====================================================================
# TCurl：把自架 Supabase 的資料（auth.users / auth.identities / 所有 public 表）
# 匯入 Supabase Cloud。步驟與回復方式見 docs/superpowers/specs/2026-11-02-data-import.md
#
# 用法：
#   scripts/import-data.sh --dry-run [--emit-driver PATH]
#       只在本機檢查抽取檔（MANIFEST / SHA256SUMS）並產生 driver SQL；不連線、不需要 psql。
#   scripts/import-data.sh [--yes]
#       1) 唯讀預檢（schema 已套用、身分可用、目標表皆為空）
#       2) 確認後，以 psql -v ON_ERROR_STOP=1 --single-transaction 依 FK 順序匯入
#          （任何錯誤 → 整個交易 rollback，Cloud 不會留下半套資料）
#       3) 交易內重設序列、REFRESH materialized views、比對筆數（不符即 rollback）
#       4) 交易後 ANALYZE，並列出每張表「預期 / 實際」筆數
#
# 設定：
#   ~/.config/tcurl/supabase.env 內的 SUPABASE_DB_URL（必要；本腳本不會建立或修改此檔）
#     - 建議用 Session pooler（port 5432）或 Direct connection；不要用 Transaction pooler（6543）
#     - 選用 SUPABASE_DB_PASSWORD：URL 不含密碼時，以 PGPASSWORD 傳給 psql
#   環境變數（選用）：
#     TCURL_SUPABASE_ENV_FILE  覆寫 env 檔路徑
#     TCURL_EXTRACT_DIR        覆寫抽取檔目錄
#
# 需要 psql（本機未安裝時：brew install libpq，並把 "$(brew --prefix libpq)/bin" 加進 PATH）。
# 本腳本不會印出連線字串、密碼或任何資料列內容；只印筆數與布林檢查結果。
# =====================================================================
set -euo pipefail
umask 077

ENV_FILE="${TCURL_SUPABASE_ENV_FILE:-$HOME/.config/tcurl/supabase.env}"
EXTRACT_DIR="${TCURL_EXTRACT_DIR:-$HOME/Desktop/projects/urlpj/supabase-2026-11-02/extract}"
CHECK_NAME="urls_original_url_http_check"
CHECK_EXPR="original_url ~* '^https?://'"

DRY_RUN=0
ASSUME_YES=0
EMIT_DRIVER=""

usage() {
  sed -n '2,30p' "$0" | sed 's/^# \{0,1\}//'
}

die() { printf 'ERROR: %s\n' "$*" >&2; exit 1; }
info() { printf '==> %s\n' "$*"; }

while [ $# -gt 0 ]; do
  case "$1" in
    --dry-run) DRY_RUN=1 ;;
    --yes|-y) ASSUME_YES=1 ;;
    --emit-driver)
      [ $# -ge 2 ] || die "--emit-driver 需要路徑"
      EMIT_DRIVER="$2"; shift ;;
    -h|--help) usage; exit 0 ;;
    *) die "未知參數：$1（--help 看用法）" ;;
  esac
  shift
done

# ---------------------------------------------------------------------
# 1. 抽取檔檢查
# ---------------------------------------------------------------------
[ -d "$EXTRACT_DIR" ] || die "找不到抽取目錄：$EXTRACT_DIR"
case "$EXTRACT_DIR" in
  *"'"*) die "抽取目錄路徑不可含單引號" ;;
esac
[ -f "$EXTRACT_DIR/MANIFEST.tsv" ] || die "缺少 $EXTRACT_DIR/MANIFEST.tsv"
[ -f "$EXTRACT_DIR/SHA256SUMS" ] || die "缺少 $EXTRACT_DIR/SHA256SUMS"

file_mode() { stat -c '%a' "$1" 2>/dev/null || stat -f '%Lp' "$1"; }
dir_mode="$(file_mode "$EXTRACT_DIR")"
if [ "$dir_mode" != "700" ]; then
  printf 'WARN: %s 權限是 %s（預期 700；內含個資）\n' "$EXTRACT_DIR" "$dir_mode" >&2
fi

info "驗證抽取檔 SHA-256"
if command -v shasum >/dev/null 2>&1; then
  (cd "$EXTRACT_DIR" && shasum -a 256 -c --quiet SHA256SUMS) || die "SHA-256 不符，抽取檔可能被改動"
else
  (cd "$EXTRACT_DIR" && sha256sum -c --quiet SHA256SUMS) || die "SHA-256 不符，抽取檔可能被改動"
fi

# MANIFEST.tsv：order<TAB>file<TAB>table<TAB>rows<TAB>columns（已依 FK 安全順序排序）
FILES=()
TABLES=()
ROWS=()
while IFS="$(printf '\t')" read -r m_order m_file m_table m_rows m_cols; do
  [ "$m_order" = "order" ] && continue
  [ -n "$m_file" ] || continue
  printf '%s' "$m_file" | grep -Eq '^[0-9]{2}_[a-z_]+\.sql$' || die "MANIFEST 檔名格式不符：$m_file"
  printf '%s' "$m_table" | grep -Eq '^(auth|public)\.[a-z_]+$' || die "MANIFEST 表名格式不符：$m_table"
  printf '%s' "$m_rows" | grep -Eq '^[0-9]+$' || die "MANIFEST 筆數格式不符：$m_rows"
  [ -f "$EXTRACT_DIR/$m_file" ] || die "缺少抽取檔：$m_file"
  FILES+=("$m_file")
  TABLES+=("$m_table")
  ROWS+=("$m_rows")
done < "$EXTRACT_DIR/MANIFEST.tsv"
[ "${#FILES[@]}" -gt 0 ] || die "MANIFEST 是空的"

# FK 安全順序：auth.users 必須最先，auth.identities 與 public 表在其後
[ "${TABLES[0]}" = "auth.users" ] || die "MANIFEST 第一個必須是 auth.users"

info "匯入計畫（依序）："
i=0
while [ $i -lt ${#FILES[@]} ]; do
  printf '    %-32s %-26s %10s rows\n' "${FILES[$i]}" "${TABLES[$i]}" "${ROWS[$i]}"
  i=$((i + 1))
done

# ---------------------------------------------------------------------
# 2. 產生 driver SQL（只含 \i 參照與 DDL / 檢查，不含資料）
# ---------------------------------------------------------------------
DRIVER="$(mktemp "${TMPDIR:-/tmp}/tcurl-import-driver.XXXXXX")"
cleanup() { rm -f "$DRIVER"; }
trap cleanup EXIT

values_list=""
i=0
while [ $i -lt ${#TABLES[@]} ]; do
  [ -n "$values_list" ] && values_list="$values_list, "
  values_list="$values_list('${TABLES[$i]}', ${ROWS[$i]})"
  i=$((i + 1))
done

{
  echo "-- generated by scripts/import-data.sh — run with: psql -X -v ON_ERROR_STOP=1 --single-transaction -f <this file>"
  echo "\\set ON_ERROR_STOP on"
  echo "SET statement_timeout = 0;"
  echo "SET lock_timeout = '30s';"
  echo ""
  echo "-- 前置條件（交易內再檢查一次）：schema 已套用、目標表全為空"
  echo "DO \$tcurl\$"
  echo "DECLARE r record; v bigint;"
  echo "BEGIN"
  echo "  IF to_regclass('public.urls') IS NULL THEN"
  echo "    RAISE EXCEPTION 'public.urls 不存在：請先套用 supabase/migrations/20261102040837_init_from_selfhosted.sql';"
  echo "  END IF;"
  echo "  FOR r IN SELECT * FROM (VALUES $values_list) AS t(tbl, expected) LOOP"
  echo "    EXECUTE format('SELECT count(*) FROM %s', r.tbl::regclass) INTO v;"
  echo "    IF v <> 0 THEN"
  echo "      RAISE EXCEPTION '目標表 % 已有 % 筆資料；中止（見 data-import.md 的回復步驟）', r.tbl, v;"
  echo "    END IF;"
  echo "  END LOOP;"
  echo "END"
  echo "\$tcurl\$;"
  echo ""
  echo "-- 停用 trigger（含 auth.users 的 on_auth_user_created、urls 的 url_audit_trigger）與 FK 檢查"
  echo "SET session_replication_role = replica;"
  echo ""
  echo "-- [FIX-1] 的 CHECK 是 NOT VALID，但 COPY 仍會檢查 CHECK；"
  echo "-- 既有 1 筆非 http(s) 網址要保留，所以在同一交易內暫時移除、匯入後以 NOT VALID 加回。"
  echo "ALTER TABLE public.urls DROP CONSTRAINT $CHECK_NAME;"
  echo ""
  i=0
  while [ $i -lt ${#FILES[@]} ]; do
    echo "\\echo '--> ${TABLES[$i]}'"
    echo "\\i '$EXTRACT_DIR/${FILES[$i]}'"
    i=$((i + 1))
  done
  echo ""
  echo "SET session_replication_role = replica;"
  echo "ALTER TABLE public.urls ADD CONSTRAINT $CHECK_NAME CHECK ($CHECK_EXPR) NOT VALID;"
  echo ""
  echo "-- 重設 public schema 內所有「由欄位擁有」的序列（目前 schema 全用 uuid，預期 0 個）"
  echo "DO \$tcurl\$"
  echo "DECLARE r record; v_max bigint; n int := 0;"
  echo "BEGIN"
  echo "  FOR r IN"
  echo "    SELECT s.oid::regclass AS seq, d.refobjid::regclass AS tbl, a.attname AS col"
  echo "    FROM pg_class s"
  echo "    JOIN pg_namespace ns ON ns.oid = s.relnamespace"
  echo "    JOIN pg_depend d ON d.classid = 'pg_class'::regclass AND d.objid = s.oid"
  echo "                     AND d.refclassid = 'pg_class'::regclass AND d.deptype IN ('a', 'i')"
  echo "    JOIN pg_attribute a ON a.attrelid = d.refobjid AND a.attnum = d.refobjsubid"
  echo "    WHERE s.relkind = 'S' AND ns.nspname = 'public'"
  echo "  LOOP"
  echo "    EXECUTE format('SELECT max(%I) FROM %s', r.col, r.tbl) INTO v_max;"
  echo "    PERFORM setval(r.seq, COALESCE(v_max, 1), v_max IS NOT NULL);"
  echo "    n := n + 1;"
  echo "  END LOOP;"
  echo "  RAISE NOTICE 'sequences reset: %', n;"
  echo "END"
  echo "\$tcurl\$;"
  echo ""
  echo "REFRESH MATERIALIZED VIEW public.url_daily_stats;"
  echo "REFRESH MATERIALIZED VIEW public.url_recent_stats;"
  echo ""
  echo "-- 交易內比對筆數：任何一張不符即丟例外 → psql ON_ERROR_STOP → 整個交易 rollback"
  echo "DO \$tcurl\$"
  echo "DECLARE r record; v bigint; bad int := 0;"
  echo "BEGIN"
  echo "  FOR r IN SELECT * FROM (VALUES $values_list) AS t(tbl, expected) LOOP"
  echo "    EXECUTE format('SELECT count(*) FROM %s', r.tbl::regclass) INTO v;"
  echo "    RAISE NOTICE '% expected=% actual=%', r.tbl, r.expected, v;"
  echo "    IF v <> r.expected THEN bad := bad + 1; END IF;"
  echo "  END LOOP;"
  echo "  IF bad > 0 THEN"
  echo "    RAISE EXCEPTION '% 張表筆數不符，rollback', bad;"
  echo "  END IF;"
  echo "END"
  echo "\$tcurl\$;"
  echo ""
  echo "RESET session_replication_role;"
} > "$DRIVER"

if [ -n "$EMIT_DRIVER" ]; then
  cp "$DRIVER" "$EMIT_DRIVER"
  chmod 600 "$EMIT_DRIVER"
  info "driver SQL 已寫到：$EMIT_DRIVER"
fi

if [ "$DRY_RUN" -eq 1 ]; then
  info "dry-run 完成：抽取檔完整、driver SQL 已產生（未連線、未寫入任何資料庫）"
  exit 0
fi

# ---------------------------------------------------------------------
# 3. psql 與連線設定
# ---------------------------------------------------------------------
if ! command -v psql >/dev/null 2>&1; then
  die "找不到 psql。請先：brew install libpq && export PATH=\"\$(brew --prefix libpq)/bin:\$PATH\"（libpq 是 keg-only）"
fi

[ -f "$ENV_FILE" ] || die "找不到 $ENV_FILE（請自行建立並放入 SUPABASE_DB_URL；本腳本不會建立它）"
env_mode="$(file_mode "$ENV_FILE")"
case "$env_mode" in
  600|400) ;;
  *) printf 'WARN: %s 權限是 %s，建議 chmod 600\n' "$ENV_FILE" "$env_mode" >&2 ;;
esac

# 只讀取需要的兩個鍵（不 source 整個檔案）；去掉 export 前綴與成對引號
read_env_key() {
  local key="$1" val
  val="$(sed -nE "s/^[[:space:]]*(export[[:space:]]+)?${key}[[:space:]]*=[[:space:]]*//p" "$ENV_FILE" | tail -n 1)"
  val="${val%$'\r'}"
  case "$val" in
    \"*\") val="${val#\"}"; val="${val%\"}" ;;
    \'*\') val="${val#\'}"; val="${val%\'}" ;;
  esac
  printf '%s' "$val"
}

DB_URL="$(read_env_key SUPABASE_DB_URL)"
[ -n "$DB_URL" ] || die "$ENV_FILE 裡沒有 SUPABASE_DB_URL"
case "$DB_URL" in
  postgres://*|postgresql://*) ;;
  *) die "SUPABASE_DB_URL 必須是 postgres:// 或 postgresql:// 開頭（內容不顯示）" ;;
esac
case "$DB_URL" in
  *:6543/*|*:6543) die "SUPABASE_DB_URL 指向 Transaction pooler（6543）；請改用 Session pooler（5432）或 Direct connection" ;;
esac
DB_PASSWORD="$(read_env_key SUPABASE_DB_PASSWORD)"
if [ -n "$DB_PASSWORD" ]; then
  export PGPASSWORD="$DB_PASSWORD"
fi
unset DB_PASSWORD
export PGAPPNAME="tcurl-import-data"
export PGCONNECT_TIMEOUT=15
# 連線字串未指定 sslmode 時，強制 require
export PGSSLMODE="${PGSSLMODE:-require}"

run_psql() {
  # 連線字串只經由參數傳給 psql，不會被 echo
  psql -X -v ON_ERROR_STOP=1 -d "$DB_URL" "$@"
}

# ---------------------------------------------------------------------
# 4. 唯讀預檢
# ---------------------------------------------------------------------
info "唯讀預檢"
count_sql=""
i=0
while [ $i -lt ${#TABLES[@]} ]; do
  [ -n "$count_sql" ] && count_sql="$count_sql UNION ALL "
  count_sql="${count_sql}SELECT '${TABLES[$i]}', count(*) FROM ${TABLES[$i]}"
  i=$((i + 1))
done

pre="$(run_psql -At -F '|' <<SQL
SELECT
  to_regclass('public.urls') IS NOT NULL,
  COALESCE((SELECT pg_get_userbyid(relowner) = current_user FROM pg_class WHERE oid = to_regclass('public.urls')), false),
  EXISTS (SELECT 1 FROM pg_constraint WHERE conname = '$CHECK_NAME' AND conrelid = to_regclass('public.urls')),
  (SELECT rolbypassrls OR rolsuper FROM pg_roles WHERE rolname = current_user),
  EXISTS (SELECT 1 FROM pg_trigger WHERE tgrelid = 'auth.users'::regclass AND tgname = 'on_auth_user_created'),
  NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgrelid = 'auth.users'::regclass AND tgname = 'on_auth_user_copy_email'),
  has_table_privilege('auth.users', 'INSERT') AND has_table_privilege('auth.identities', 'INSERT'),
  current_setting('server_version_num');
SQL
)" || die "預檢連線或查詢失敗（請確認 SUPABASE_DB_URL、網路、IPv4/IPv6 與密碼）"

IFS='|' read -r has_urls is_owner has_check can_bypass has_trigger no_copy_email can_insert_auth server_ver <<EOF
$pre
EOF
printf '    schema 已套用 (public.urls)          : %s\n' "$has_urls"
printf '    目前角色擁有 public.urls             : %s\n' "$is_owner"
printf '    %s 存在 : %s\n' "$CHECK_NAME" "$has_check"
printf '    目前角色可繞過 RLS（COPY auth.*）     : %s\n' "$can_bypass"
printf '    auth.users on_auth_user_created 存在 : %s\n' "$has_trigger"
printf '    沒有 on_auth_user_copy_email         : %s\n' "$no_copy_email"
printf '    可 INSERT auth.users / identities     : %s\n' "$can_insert_auth"
printf '    server_version_num                   : %s\n' "$server_ver"
[ "$has_urls" = "t" ] || die "請先套用 supabase/migrations/20261102040837_init_from_selfhosted.sql"
[ "$is_owner" = "t" ] || die "目前角色不是 public.urls 的擁有者，無法暫時移除 CHECK；請用套用 migration 的同一個角色（postgres）"
[ "$has_check" = "t" ] || die "找不到 $CHECK_NAME（migration 版本不符？）"
[ "$can_bypass" = "t" ] || die "目前角色沒有 BYPASSRLS，無法 COPY 進啟用 RLS 的 auth.users"
[ "$can_insert_auth" = "t" ] || die "目前角色沒有 auth.users / auth.identities 的 INSERT 權限"
[ "$has_trigger" = "t" ] || die "auth.users 上沒有 on_auth_user_created（migration 未完整套用？）"
[ "$no_copy_email" = "t" ] || die "auth.users 上存在 on_auth_user_copy_email（不應搬移的 Keycloak 補丁）；請先移除"

info "目標表目前筆數（必須全為 0）"
pre_counts="$(run_psql -At -F '|' -c "$count_sql")" || die "查詢目標表筆數失敗"
nonempty=0
while IFS='|' read -r t c; do
  [ -n "$t" ] || continue
  printf '    %-26s %10s\n' "$t" "$c"
  [ "$c" = "0" ] || nonempty=1
done <<EOF
$pre_counts
EOF
[ "$nonempty" -eq 0 ] || die "目標表已有資料（可能有人已用 Google 登入過 Cloud）；中止。處理方式見 data-import.md"

# ---------------------------------------------------------------------
# 5. 匯入（單一交易）
# ---------------------------------------------------------------------
if [ "$ASSUME_YES" -ne 1 ]; then
  printf '即將以單一交易匯入上述 %s 個檔案到 Supabase Cloud。輸入 IMPORT 繼續：' "${#FILES[@]}"
  read -r answer
  [ "$answer" = "IMPORT" ] || die "已取消"
fi

info "匯入中（任何錯誤會整個 rollback）"
run_psql -q --single-transaction -f "$DRIVER"
info "交易已 COMMIT"

# ---------------------------------------------------------------------
# 6. 匯入後：ANALYZE 與筆數比對
# ---------------------------------------------------------------------
analyze_sql=""
i=0
while [ $i -lt ${#TABLES[@]} ]; do
  analyze_sql="${analyze_sql}ANALYZE ${TABLES[$i]}; "
  i=$((i + 1))
done
run_psql -q -c "$analyze_sql" >/dev/null

info "筆數比對（預期 = 自架 dump，實際 = Cloud）"
post_counts="$(run_psql -At -F '|' -c "$count_sql")" || die "查詢匯入後筆數失敗"
printf '    %-26s %10s %10s  %s\n' "table" "expected" "actual" "result"
mismatch=0
while IFS='|' read -r t c; do
  [ -n "$t" ] || continue
  exp=""
  i=0
  while [ $i -lt ${#TABLES[@]} ]; do
    [ "${TABLES[$i]}" = "$t" ] && exp="${ROWS[$i]}"
    i=$((i + 1))
  done
  if [ "$c" = "$exp" ]; then res="OK"; else res="MISMATCH"; mismatch=1; fi
  printf '    %-26s %10s %10s  %s\n' "$t" "$exp" "$c" "$res"
done <<EOF
$post_counts
EOF

info "其他檢查"
run_psql -At -F '|' <<'SQL' | while IFS='|' read -r k v; do printf '    %-48s %s\n' "$k" "$v"; done
SELECT 'urls 不符合 http(s) CHECK 的既有筆數（預期 1）', count(*)::text FROM public.urls WHERE original_url !~* '^https?://'
UNION ALL
SELECT 'urls_original_url_http_check 為 NOT VALID', (NOT convalidated)::text FROM pg_constraint WHERE conname = 'urls_original_url_http_check'
UNION ALL
SELECT 'user_profiles 與 auth.users 一一對應', ((SELECT count(*) FROM public.user_profiles p JOIN auth.users u ON u.id = p.id) = (SELECT count(*) FROM auth.users))::text
UNION ALL
SELECT 'public 表皆啟用 RLS', bool_and(c.relrowsecurity)::text FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace WHERE n.nspname = 'public' AND c.relkind = 'r'
UNION ALL
SELECT 'url_clicks policy 數（預期 0）', count(*)::text FROM pg_policies WHERE schemaname = 'public' AND tablename = 'url_clicks'
UNION ALL
SELECT 'audit_logs INSERT policy 數（預期 0）', count(*)::text FROM pg_policies WHERE schemaname = 'public' AND tablename = 'audit_logs' AND cmd IN ('INSERT', 'ALL');
SQL

if [ "$mismatch" -ne 0 ]; then
  die "筆數不符（交易已提交，請依 data-import.md 的回復步驟處理）"
fi
info "完成。接著依 data-import.md 的「匯入後檢查」驗證 RLS 與統計 RPC。"
